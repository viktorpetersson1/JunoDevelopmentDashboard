#!/usr/bin/env node
/**
 * generate-seed-sql.mjs
 *
 * Reads BASELINE_PROJECTS from public/data.js (the canonical vanilla seed),
 * converts each to the atlas.projects DB column shape (dollars → cents,
 * decimals → basis points), and prints SQL INSERT statements suitable
 * for `mcp__supabase__apply_migration`.
 *
 * Output: stdout. Pipe to a file or copy into the MCP call.
 *
 *   node atlas/scripts/generate-seed-sql.mjs > seed-baseline-projects.sql
 */

import { BASELINE_PROJECTS } from '../../public/data.js';

const toCents = (dollars) =>
  dollars == null || Number.isNaN(dollars) ? null : Math.round(dollars * 100);
const toBps = (decimal) =>
  decimal == null || Number.isNaN(decimal) ? null : Math.round(decimal * 10000);

const sqlVal = (v) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  if (typeof v === 'object') return `'${JSON.stringify(v).replaceAll("'", "''")}'::jsonb`;
  // text — escape single quotes
  return `'${String(v).replaceAll("'", "''")}'`;
};

function projectToInsertRow(p) {
  return {
    project_key: p.id,
    name: p.name,
    address: p.address,
    google_maps_url: p.google_maps_url,
    entity_spv: p.entity_spv,
    market_id: p.market ?? 'default',
    asset_type: p.asset_type,
    status: p.status,
    stage: p.stage,
    purchase_date: p.purchase_date,
    sourcing_months: p.sourcing_months ?? 0,
    permitting_preconstruction_months: p.permitting_preconstruction_months ?? 0,
    construction_months: p.construction_months ?? 0,
    sales_months: p.sales_months ?? 0,
    villa_sqft_ag: p.villa_sqft_ag ?? 0,
    villa_sqft_bg: p.villa_sqft_bg ?? 0,
    land_cost_cents: toCents(p.land_cost_usd) ?? 0,
    build_cost_per_sqft_cents: toCents(p.build_cost_per_sqft),
    soft_costs_lump_sum_cents: toCents(p.soft_costs_lump_sum) ?? 0,
    soft_costs_breakdown: null,
    lender_name: p.lender_name,
    senior_ltv_bps: toBps(p.senior_ltv_pct) ?? 7500,
    interest_rate_bps: toBps(p.interest_rate_apr),
    contingency_bps: toBps(p.contingency_pct),
    origination_fee_bps: toBps(p.origination_fee_pct) ?? 100,
    exit_fee_bps: toBps(p.exit_fee_pct) ?? 50,
    interest_reserve_cents: toCents(p.interest_reserve_usd) ?? 0,
    loan_servicing_fee_cents: toCents(p.loan_servicing_fee_usd) ?? 0,
    closing_costs_cents: toCents(p.closing_costs_usd) ?? 0,
    other_fees: null,
    sale_price_override_cents: toCents(p.sale_price_override_usd),
    sale_price_per_sqft_override_cents: toCents(p.sale_price_per_sqft_override),
    target_margin_bps: toBps(p.target_margin),
    listing_date: p.listing_date,
    under_contract_date: p.under_contract_date,
    closing_date: p.closing_date,
    listing_price_cents: toCents(p.listing_price_usd),
    actual_sale_price_cents: toCents(p.actual_sale_price_usd),
    build_cost_curve: p.build_cost_curve,
  };
}

const COLS = [
  'project_key', 'name', 'address', 'google_maps_url', 'entity_spv',
  'market_id', 'asset_type', 'status', 'stage',
  'purchase_date', 'sourcing_months', 'permitting_preconstruction_months',
  'construction_months', 'sales_months', 'villa_sqft_ag', 'villa_sqft_bg',
  'land_cost_cents', 'build_cost_per_sqft_cents', 'soft_costs_lump_sum_cents',
  'soft_costs_breakdown', 'lender_name', 'senior_ltv_bps', 'interest_rate_bps',
  'contingency_bps', 'origination_fee_bps', 'exit_fee_bps',
  'interest_reserve_cents', 'loan_servicing_fee_cents', 'closing_costs_cents',
  'other_fees', 'sale_price_override_cents', 'sale_price_per_sqft_override_cents',
  'target_margin_bps', 'listing_date', 'under_contract_date', 'closing_date',
  'listing_price_cents', 'actual_sale_price_cents', 'build_cost_curve',
];

console.log('-- BASELINE_PROJECTS seed for atlas.projects');
console.log('-- Generated by atlas/scripts/generate-seed-sql.mjs');
console.log('-- Idempotent: ON CONFLICT (project_key, version) DO NOTHING (since fresh inserts always go to version=1)');
console.log('');

for (const p of BASELINE_PROJECTS) {
  const row = projectToInsertRow(p);
  const values = COLS.map((c) => sqlVal(row[c])).join(', ');
  console.log(`INSERT INTO atlas.projects (${COLS.join(', ')}) VALUES (${values}) ON CONFLICT (project_key, version) DO NOTHING;`);
}
